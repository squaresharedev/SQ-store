import { chromium } from "playwright";
import assert from "node:assert";
const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium" });
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
await page.goto("http://localhost:3000/dev/product-form?mode=edit", { waitUntil: "networkidle", timeout: 120000 });
// The failing spec's own assertions, against the harness fixture.
const section = page.locator("[data-product-section='shipping']");
assert(await section.isVisible(), "section visible");
assert.equal(await section.locator("textarea").count(), 0);
assert(await section.getByText("Ships in 1–2 working days").isVisible(), "dispatch line");
assert(await section.getByRole("button", { name: "Edit" }).isVisible(), "edit button");
assert(await section.getByText("Store terms").isVisible(), "store terms summary");
await section.getByRole("combobox").click();
await page.getByRole("option", { name: /Bulky items/ }).click();
assert(await section.getByText("Ships in 5–7 days").isVisible(), "profile dispatch");
assert.equal(await section.getByText("Ships in 1–2 working days").count(), 0);
assert(await section.getByText("Bulky items").first().isVisible(), "summary names profile");
console.log("spec assertions: all pass");
await page.locator("[data-product-section='media']").screenshot({ path: process.argv[2] });
await browser.close();
